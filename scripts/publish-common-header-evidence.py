def date_shape(value):
 if value=='':return 'empty'
 if value.isspace():return 'whitespace-only'
 if re.fullmatch(r'\d{2}/\d{2}/\d{4}',value):return 'dd-mm-yyyy-slashes'
 if re.fullmatch(r'\d{4}-\d{2}-\d{2}',value):return 'yyyy-mm-dd'
 return 'other'

